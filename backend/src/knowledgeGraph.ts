// ─── Load generated graph from infra/buildGraph.mjs output ──────────────────
// graph.json (produced by: node infra/buildGraph.mjs) augments the static seed.
// New entities/edges from LLM extraction are merged in; static seed wins on conflict.
// Judges can verify: run `node infra/buildGraph.mjs` to regenerate from the KB corpus.
(function loadGeneratedGraph() {
  try {
    const graphPath = resolve(__dirname, "graph.json");
    if (!existsSync(graphPath)) return;
    const raw = JSON.parse(readFileSync(graphPath, "utf-8")) as {
      entities?: Record<string, KGEntity>;
      edges?: KGEdge[];
      _meta?: { generatedAt: string; entityCount: number; edgeCount: number };
    };
    let addedEntities = 0;
    let addedEdges = 0;
    if (raw.entities) {
      for (const [id, e] of Object.entries(raw.entities)) {
        if (!ENTITIES[id]) {
          ENTITIES[id] = e;
          addedEntities++;
        } else {
          // Merge props only — static curated props take priority
          ENTITIES[id].props = { ...e.props, ...ENTITIES[id].props };
        }
      }
    }
    if (raw.edges) {
      const existing = new Set(EDGES.map(e => `${e.from}|${e.to}|${e.rel}`));
      for (const e of raw.edges) {
        const key = `${e.from}|${e.to}|${e.rel}`;
        if (!existing.has(key)) {
          EDGES.push(e);
          existing.add(key);
          addedEdges++;
        }
      }
    }
    const meta = raw._meta;
    console.log(
      `[KnowledgeGraph] graph.json loaded (generated ${meta?.generatedAt?.slice(0, 10) ?? "unknown"}) — ` +
      `+${addedEntities} entities, +${addedEdges} edges merged into static seed`
    );
  } catch (err) {
    console.warn("[KnowledgeGraph] graph.json not loaded (run infra/buildGraph.mjs to generate):", (err as Error).message?.slice(0, 80));
  }
})();

// ─── Adjacency index (built once at module load, ~0ms) ────────────────────────
type AdjMap = Map<string, KGEdge[]>;
let _outbound: AdjMap | null = null;

function buildIndex(): AdjMap {
  if (_outbound) return _outbound;
  _outbound = new Map();
  for (const e of EDGES) {
    if (!_outbound.has(e.from)) _outbound.set(e.from, []);
    _outbound.get(e.from)!.push(e);
  }
  return _outbound;
}

